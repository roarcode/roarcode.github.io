"""Splits the UPGRADE parts out of components.css / ui.js into standalone files Lead Engineer can drop into the live build:
   upgrade.css = prerequisite helpers (.mono/.label, .icon-btn, .chip*, .btn--sm) + CSS §17 (all new components)
   upgrade.js  = the <upgrade> block of ui.js (ToC scroll-spy, read progress, checklist/tracker, gallery, lightbox, tab bar search hook)
Run:  python3 src/build_upgrade_bundle.py"""
import pathlib, re
D = pathlib.Path(__file__).resolve().parent.parent
css = (D/'components.css').read_text()
i = css.index('/* ==========================================================================\n   17. UPGRADE')
upgrade = css[i:]
want = re.compile(r'^(\.mono, \.label|\.icon-btn\b|\.chip\b|a\.chip:hover|\.chip--filter|\.chip-row\b|\.btn--sm)')
support = [l for l in css[:i].split('\n') if want.match(l)]
head = '/* upgrade.css — GENERATED by src/build_upgrade_bundle.py from components.css (do not edit). Needs design/tokens.css. Unofficial fan site — not affiliated with Rockstar Games. */\n/* ---- prerequisite helpers (copied verbatim from components.css §0/§2/§3; skip any you already ship) ---- */\n'
(D/'upgrade.css').write_text(head + '\n'.join(support) + '\n\n' + upgrade)
js = (D/'ui.js').read_text()
a = js.index('// <upgrade>'); b = js.index('// </upgrade>')
block = js[a:b]
(D/'upgrade.js').write_text('/* upgrade.js — GENERATED from ui.js by src/build_upgrade_bundle.py (do not edit). Dependency-free, progressive enhancement. */\n(() => {\n  const $ = (s, r = document) => r.querySelector(s), $$ = (s, r = document) => [...r.querySelectorAll(s)];\n  ' + block + '})();\n')
import subprocess; subprocess.run(['node','--check',str(D/'upgrade.js')],check=True)
print('upgrade.css', (D/'upgrade.css').stat().st_size, 'B; upgrade.js', (D/'upgrade.js').stat().st_size, 'B; support rules', len(support))
